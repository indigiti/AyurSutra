#!/usr/bin/env python3
"""Expand the CC BY-SA Wikisource source edition as *unproofread* text, never as reviewed editorial content.

The input is a draft generated by scripts/stage-madhava-wikisource.py. The source hash
is pinned and all 67 chapters must be present before any output is written.
"""
import argparse,hashlib,json,re
# Source corpus does not confer approval of its medical assertions.
from pathlib import Path
SOURCE_HASH="d726be9abd42def48814c5dec748b295e6a887cc9697c9df3deec8e41bacd44b"
SOURCE_URL="https://sa.wikisource.org/wiki/माधवनिदानम्?oldid=75848"
def load(path):return json.loads(Path(path).read_text(encoding="utf-8"))
def main():
 p=argparse.ArgumentParser()
 p.add_argument("--draft",required=True,type=Path)
 p.add_argument("--storage",required=True,type=Path)
 p.add_argument("--source-sha256",required=True)
 p.add_argument("--apply",action="store_true")
 a=p.parse_args()
 if a.source_sha256!=SOURCE_HASH:raise ValueError("Unrecognized Wikisource source revision checksum")
 data=load(a.draft)
 entries=data.get("chapters",[])
 if data.get("format")!="ayursutra-ay-1" or len(entries)!=67:
  raise ValueError("Exactly 67 draft chapters from the registered edition required")
 storage=a.storage.resolve()
 corpus=storage/"corpus"
 chapters_file=corpus/"sections/madhava-nidana-madhavanidana.json"
 manifest_file=corpus/"manifest.json"
 books_file=storage/"books.json"
 if not all(path.is_file() for path in (chapters_file,manifest_file,books_file)):
  raise ValueError("Required corpus files are missing")
 original=load(chapters_file); manifest=load(manifest_file);books=load(books_file)
 if original.get("book_id")!="madhava-nidana" or len(original.get("chapters",[]))!=1:
  raise ValueError("Only first-chapter seed can be expanded; existing source may have changed")
 if original["chapters"][0].get("chapter_slug")!="chapter-01":raise ValueError("Seed chapter mismatch")
 all_chapters=list(original["chapters"])
 index_items=[]
 for number,item in enumerate(entries,2):
  slug=f"chapter-{number:02d}"
  if (item.get("book_id"),item.get("section_slug"),item.get("chapter_slug"))!=("madhava-nidana","madhavanidana",slug):
   raise ValueError(f"Unexpected chapter mapping: {slug}")
  if item.get("source_url")!=SOURCE_URL:raise ValueError("Unpinned or mismatched source URL")
  title=item.get("title")
  if not isinstance(title,str) or not title or len(title)>240:raise ValueError("Invalid source heading")
  lines=item.get("passages")
  if not isinstance(lines,list) or len(lines)<3 or len(lines)>400:raise ValueError("Invalid passage count")
  passages=[]
  for position,line in enumerate(lines,1):
   text=line.get("text_devanagari","")
   if not isinstance(text,str) or not text.strip() or len(text)>500 or any(mark in text for mark in ("{{","}}","[[","]]","<",">")):
    raise ValueError(f"Unexpected markup in {slug} source line {position}")
   if line.get("reference")!=f"source-line-{position:04d}":raise ValueError("Unstable source line reference")
   passages.append({"id":f"madhava-{number:02d}-{position:04d}",
     "reference":line["reference"],"text_devanagari":text.strip(),"text_iast":"",
     "translation_en":"","commentary":"","key_terms":[]})
  all_chapters.append({"id":f"madhava-nidana/madhavanidana/{slug}",
   "book_id":"madhava-nidana","section_slug":"madhavanidana","chapter_slug":slug,
   "chapter_number":number,"title":title,"source_title":title,
   "source_url":SOURCE_URL,"source_license":"Sanskrit Wikisource CC BY-SA 4.0; attribution to contributors at source revision 75848",
   "source_type":"Devanagari source line transcription; line boundaries are not verified verse numbers",
   "verification":"Unproofread digital source; not scholarly reviewed, translated, or clinical advice",
   "status":"source-edition","passages":passages})
  index_items.append({"slug":slug,"source_title":title,"passage_count":len(passages)})
 if len(all_chapters)!=68 or sum(len(c["passages"]) for c in all_chapters)!=3286:
  raise ValueError("Source edition count mismatch")
 target=next((b for b in manifest["books"] if b.get("id")=="madhava-nidana"),None)
 if target is None:raise ValueError("No matching source manifest book")
 assert len(target["sections"])==1
 target["sections"][0]["chapters"]+=index_items
 target["chapters"]=68
 target["passages"]=3286
 target["source_file"]="Sanskrit Wikisource revision 75848; opening chapter cross-reference mirror"
 target["source_url"]=SOURCE_URL
 target["license"]="Opening chapter cross-reference; new chapters Sanskrit Wikisource CC BY-SA 4.0, attribution in source metadata"
 target["editorial_status"]="unproofread source transcription, not scholarly reviewed; 68 original chapters, 2 catalogue appendices"
 for book in books:
  if book["id"]=="madhava-nidana":
   book["chapters_indexed"]=68;book["status"]="source-edition-unproofread"
 result={"source_revision":75848,"source_sha256":SOURCE_HASH,
  "new_chapters":67,"new_lines":3265,"total_source_chapters":68,
  "total_source_passages":3286,"reviewed":False,"published_editorial":False}
 if a.apply:
  # Validate everything in memory before writing; intended for source-tracked git workflow.
  for path,payload in [(chapters_file,{**original,"chapters":all_chapters}),
                       (manifest_file,manifest),(books_file,books)]:
   path.write_text(json.dumps(payload,ensure_ascii=False,separators=(",",":"),indent=1)+"\n",encoding="utf-8")
 print(json.dumps(result,ensure_ascii=False))
if __name__=="__main__": main()
